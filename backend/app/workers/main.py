"""arq worker settings.

Jobs are auto-discovered: any `async def job_*(ctx, ...)` in a module under app/workers/jobs/
is registered. A module can also expose `CRON_JOBS: list[arq.cron.CronJob]` for scheduled jobs;
cron times are interpreted in Africa/Cairo. Do not edit this file to add a job.

Run with: uv run poe worker
"""

import importlib
import inspect
import logging
import pkgutil
from collections.abc import Callable
from typing import Any, ClassVar
from zoneinfo import ZoneInfo

from arq.connections import RedisSettings
from arq.cron import CronJob

from app.config import settings
from app.workers import jobs as jobs_package

logger = logging.getLogger("app.worker")


def discover_jobs() -> tuple[list[Callable[..., Any]], list[CronJob]]:
    functions: list[Callable[..., Any]] = []
    crons: list[CronJob] = []
    for module_info in sorted(pkgutil.iter_modules(jobs_package.__path__), key=lambda m: m.name):
        module = importlib.import_module(f"app.workers.jobs.{module_info.name}")
        for name, obj in inspect.getmembers(module, inspect.iscoroutinefunction):
            if name.startswith("job_") and obj.__module__ == module.__name__:
                functions.append(obj)
        crons.extend(getattr(module, "CRON_JOBS", []))
    return functions, crons


async def startup(ctx: dict[str, Any]) -> None:
    # arq already logs its own lines; give our "app.*" loggers a handler without duplicating arq's output.
    app_logger = logging.getLogger("app")
    if not app_logger.handlers:
        handler = logging.StreamHandler()
        handler.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(name)s: %(message)s"))
        app_logger.addHandler(handler)
        app_logger.setLevel(settings.LOG_LEVEL)
        app_logger.propagate = False
    logger.info("worker started")


async def shutdown(ctx: dict[str, Any]) -> None:
    logger.info("worker stopped")


_functions, _crons = discover_jobs()


class WorkerSettings:
    functions: ClassVar[list[Callable[..., Any]]] = _functions
    cron_jobs: ClassVar[list[CronJob]] = _crons
    redis_settings = RedisSettings.from_dsn(settings.REDIS_URL)
    timezone = ZoneInfo(settings.TIMEZONE)
    on_startup = startup
    on_shutdown = shutdown
    max_jobs = 10
    job_timeout = 600

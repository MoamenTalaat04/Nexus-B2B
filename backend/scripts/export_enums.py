"""Generate the TypeScript mirror of app/models/enums.py (CONTRACTS section 1).

Deterministic: same enums → byte-identical output, so CI can diff it. Member D owns running this and
committing the generated file; this script never touches frontend/ unless you pass --out.

    uv run python -m scripts.export_enums                       # print to stdout
    uv run python -m scripts.export_enums --out ../frontend/src/lib/types.ts
    uv run python -m scripts.export_enums --check ../frontend/src/lib/types.ts   # exit 1 if out of date
"""

import argparse
import inspect
import sys
from enum import StrEnum
from pathlib import Path

from app.models import enums

HEADER = (
    "// GENERATED by backend/scripts/export_enums.py from backend/app/models/enums.py.\n"
    "// Do not edit by hand.\n"
    "// Regenerate: cd backend && uv run python -m scripts.export_enums --out ../frontend/src/lib/types.ts\n"
)


def enum_classes() -> list[type[StrEnum]]:
    found = [
        obj
        for _, obj in inspect.getmembers(enums, inspect.isclass)
        if issubclass(obj, StrEnum) and obj is not StrEnum and obj.__module__ == enums.__name__
    ]
    return sorted(found, key=lambda cls: cls.__name__)


def render() -> str:
    parts = [HEADER]
    for cls in enum_classes():
        values = [member.value for member in cls]
        union = " | ".join(f'"{v}"' for v in values)
        parts.append(f"\nexport type {cls.__name__} = {union};\n")
        items = ", ".join(f'"{v}"' for v in values)
        parts.append(f"export const {cls.__name__}Values = [{items}] as const;\n")
    mapping = ", ".join(f'{k.value}: "{v.value}"' for k, v in enums.INTENT_TO_STATUS.items())
    parts.append(f"\nexport const INTENT_TO_STATUS: Record<ReplyIntent, LeadStatus> = {{ {mapping} }};\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--out", type=Path, help="write the TypeScript file here")
    group.add_argument("--check", type=Path, help="exit 1 if this file differs from the generated output")
    args = parser.parse_args(argv)
    output = render()
    if args.check:
        current = args.check.read_text(encoding="utf-8") if args.check.exists() else ""
        if current != output:
            print(f"{args.check} is out of date; regenerate it with --out.", file=sys.stderr)
            return 1
        return 0
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output, encoding="utf-8")
        print(f"wrote {args.out}")
        return 0
    sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

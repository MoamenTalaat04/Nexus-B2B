def auth(tenant_id: uuid.UUID) -> dict[str, str]:
    token = jwt.encode(
        {"sub": str(uuid.uuid4()), "tid": str(tenant_id), "role": "owner"},
        app_settings.JWT_SECRET,
        algorithm="HS256",
    )

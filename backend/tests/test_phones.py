"""P2-2: Egyptian phone normalization."""

import pytest

from app.core.phones import is_eg_mobile, normalize_eg_phone


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("010 1234 5678", "+201012345678"),
        ("01012345678", "+201012345678"),
        ("011-1234-5678", "+201112345678"),
        ("0122 123 4567", "+201221234567"),
        ("015 5123 4567", "+201551234567"),
        ("+20 10 1234 5678", "+201012345678"),
        ("+201012345678", "+201012345678"),
        ("0020 10 1234 5678", "+201012345678"),
        ("00201012345678", "+201012345678"),
        ("201012345678", "+201012345678"),
        ("+20 010 1234 5678", "+201012345678"),
        ("1012345678", "+201012345678"),
        ("٠١٠١٢٣٤٥٦٧٨", "+201012345678"),
        ("+٢٠ ١٠ ١٢٣٤ ٥٦٧٨", "+201012345678"),
        ("۰۱۰۱۲۳۴۵۶۷۸", "+201012345678"),
        ("(010) 1234-5678", "+201012345678"),
        ("Tel: 010 1234 5678", "+201012345678"),
        ("010 1234 5678 / 011 2345 6789", "+201012345678"),
        ("02 2345 6789", "+20223456789"),
        ("0223456789", "+20223456789"),
        ("+20 2 2345 6789", "+20223456789"),
        ("03 4567890", "+2034567890"),
    ],
)
def test_normalizes(raw: str, expected: str) -> None:
    assert normalize_eg_phone(raw) == expected


@pytest.mark.parametrize(
    "raw",
    [None, "", "   ", "call us", "12345", "0000", "+1 212 555 0100", "+44 20 7946 0958", "01", "abc010"],
)
def test_garbage_is_none(raw: str | None) -> None:
    assert normalize_eg_phone(raw) is None


@pytest.mark.parametrize(
    ("e164", "mobile"),
    [
        ("+201012345678", True),
        ("+201112345678", True),
        ("+201212345678", True),
        ("+201512345678", True),
        ("+201312345678", False),
        ("+20101234567", False),
        ("+2010123456789", False),
        ("+20223456789", False),
        ("01012345678", False),
        ("", False),
        (None, False),
    ],
)
def test_is_eg_mobile(e164: str | None, mobile: bool) -> None:
    assert is_eg_mobile(e164) is mobile

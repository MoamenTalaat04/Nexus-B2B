async def test_put_validates_the_body(client: AsyncClient, tenant: Tenant) -> None:
    icp = fixture_model("icp", ICP)
    bad_icp = icp.model_dump() | {"business_size": "huge"}
    profile = {
        "company_name": "x",
        "one_liner": "x",
        "products": [],
        "differentiators": [],
    }  # missing a field
    resp = await client.put(
        "/api/v1/icp/active", json={"company_profile": profile, "icp": bad_icp}, headers=auth(tenant.id)
    )
    assert resp.status_code == 422
    error = resp.json()["error"]

def region(governorate: str, *cities: str) -> RegionTarget:
    return RegionTarget(governorate=governorate, cities=list(cities))


def test_limit_regions() -> None:
    owner = [region("Cairo", "Nasr City"), region("Giza")]
    proposed = [region("cairo", "Nasr City", "Maadi"), region("Alexandria"), region("Giza", "Dokki")]
    assert icp_builder.limit_regions(proposed, owner) == [
        region("Cairo", "Nasr City"),
        region("Giza", "Dokki"),
    ]
    # nothing valid left → the owner's regions
    assert icp_builder.limit_regions([region("Aswan")], owner) == owner
    # the owner set no regions → keep the model's
    assert icp_builder.limit_regions(proposed, []) == proposed



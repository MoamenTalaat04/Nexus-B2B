@pytest.mark.usefixtures("knowledge")
async def test_knowledge_and_settings_go_in_the_shared_cached_context(
    session: AsyncSession, tenant: Tenant, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls: list[dict[str, Any]] = []

    async def spy(run: Any, **kwargs: Any) -> Any:
        calls.append(kwargs)
        name = "profile" if kwargs["output_model"] is CompanyProfile else "icp"
        return fixture_model(name, kwargs["output_model"])

    monkeypatch.setattr(icp_builder, "llm_structured", spy)
    await icp_job.run_icp_build(session, tenant.id)

    assert [c["name"] for c in calls] == ["icp_builder.profile", "icp_builder.icp"]
    first, second = calls
    assert first["cached_context"] == second["cached_context"]  # identical prefix → provider cache hits
    assert first["system"] == second["system"] == icp_builder.SYSTEM
    assert "SECRET-KNOWLEDGE-MARKER" in first["cached_context"]
    assert "<company_files>" in first["cached_context"] and "<business_settings>" in first["cached_context"]
    assert "مصنع نور لملابس الأطفال" in first["cached_context"]  # YAML keeps Arabic readable
    for call in calls:
        assert "SECRET-KNOWLEDGE-MARKER" not in call["user"]
        assert call["tier"] == "smart" and call["effort"] == "medium"
    assert "Cairo, Giza" in second["user"]
    assert "<company_profile>" in second["user"]



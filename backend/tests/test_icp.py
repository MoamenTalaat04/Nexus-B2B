async def steps_of(session: AsyncSession, run_id: uuid.UUID) -> list[AgentStep]:
    stmt = select(AgentStep).where(AgentStep.run_id == run_id).order_by(AgentStep.seq)
    return list((await session.execute(stmt)).scalars())


async def latest_run(session: AsyncSession, tenant_id: uuid.UUID) -> AgentRun:
    stmt = (
        select(AgentRun)
        .where(AgentRun.tenant_id == tenant_id)
        .order_by(AgentRun.created_at.desc())
        .limit(1)
        .execution_options(populate_existing=True)
    )
    return (await session.execute(stmt)).scalar_one()



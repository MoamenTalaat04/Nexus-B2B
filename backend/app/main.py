"""FastAPI entry point.

Routers are auto-discovered: any module in app/api/ that exposes a module-level `router`
(an APIRouter) is mounted under /api/v1. Do not edit this file to register a router.
"""

import importlib
import logging
import pkgutil
from typing import Any

from fastapi import APIRouter, FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from redis.asyncio import Redis
from sqlalchemy import text
from starlette.exceptions import HTTPException as StarletteHTTPException

from app import api as api_package
from app.config import settings
from app.core.errors import AppError
from app.db import engine

logging.basicConfig(level=settings.LOG_LEVEL)
logger = logging.getLogger("app")

API_PREFIX = "/api/v1"


def _error(status_code: int, code: str, message: str, **extra: Any) -> JSONResponse:
    body: dict[str, Any] = {"error": {"code": code, "message": message, **extra}}
    return JSONResponse(status_code=status_code, content=body)


def build_api_router() -> APIRouter:
    api = APIRouter(prefix=API_PREFIX)

    @api.get("/health", tags=["health"])
    async def health() -> dict[str, str]:
        db_status = redis_status = "ok"
        try:
            async with engine.connect() as conn:
                await conn.execute(text("SELECT 1"))
        except Exception as exc:  # report, don't crash
            logger.warning("health: db check failed: %s", exc)
            db_status = "error"
        try:
            redis = Redis.from_url(settings.REDIS_URL)
            try:
                await redis.ping()
            finally:
                await redis.aclose()
        except Exception as exc:
            logger.warning("health: redis check failed: %s", exc)
            redis_status = "error"
        overall = "ok" if db_status == redis_status == "ok" else "degraded"
        return {"status": overall, "db": db_status, "redis": redis_status}

    for module_info in sorted(pkgutil.iter_modules(api_package.__path__), key=lambda m: m.name):
        module = importlib.import_module(f"app.api.{module_info.name}")
        router = getattr(module, "router", None)
        if isinstance(router, APIRouter):
            api.include_router(router)
            logger.debug("mounted router app.api.%s", module_info.name)
    return api


def create_app() -> FastAPI:
    application = FastAPI(title="AI SDR API", version="0.1.0")

    application.add_middleware(
        CORSMiddleware,
        allow_origins=[settings.FRONTEND_ORIGIN],
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
    )

    @application.exception_handler(AppError)
    async def handle_app_error(_: Request, exc: AppError) -> JSONResponse:
        return _error(exc.status_code, exc.code, exc.message)

    @application.exception_handler(StarletteHTTPException)
    async def handle_http_error(_: Request, exc: StarletteHTTPException) -> JSONResponse:
        detail = exc.detail if isinstance(exc.detail, str) else "request failed"
        code = {401: "unauthorized", 403: "forbidden", 404: "not_found", 405: "method_not_allowed"}.get(
            exc.status_code, "http_error"
        )
        return _error(exc.status_code, code, detail)

    @application.exception_handler(RequestValidationError)
    async def handle_validation_error(_: Request, exc: RequestValidationError) -> JSONResponse:
        details = [{"loc": list(err.get("loc", ())), "msg": err.get("msg", "")} for err in exc.errors()]
        return _error(422, "validation_error", "Request validation failed", details=details)

    @application.exception_handler(Exception)
    async def handle_unexpected(_: Request, exc: Exception) -> JSONResponse:
        logger.exception("unhandled error", exc_info=exc)
        return _error(500, "internal_error", "Something went wrong")

    application.include_router(build_api_router())
    return application


app = create_app()

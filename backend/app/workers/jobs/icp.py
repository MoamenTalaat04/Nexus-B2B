"""job_build_icp (CONTRACTS section 10, P1-3): build the CompanyProfile + ICP and save them as a new version.

POST /api/v1/icp/generate pre-creates the run (status queued) and enqueues this job with its run_id.
"""

import logging
import uuid
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.agents import icp_builder
from app.agents.llm import LLMInvalidOutput, LLMOutputTruncated, LLMRefused
from app.core.tenancy import get_settings_for
from app.core.tracing import agent_run
from app.db import SessionLocal
from app.models.enums import AgentRunKind, StepType
from app.services import icp_service
from app.services import knowledge as knowledge_service

logger = logging.getLogger("app.jobs.icp")


class IcpBuildError(Exception):
    """A readable reason the ICP could not be built; stored as the run's error and shown in the UI."""


async def load_knowledge_text(session: AsyncSession, tenant_id: uuid.UUID) -> str:
    """The tenant's ready knowledge files as one text (A's P1-1 service); "" when there are none."""
    return await knowledge_service.get_knowledge_text(session, tenant_id)


async def run_icp_build(
    session: AsyncSession, tenant_id: uuid.UUID, *, run_id: uuid.UUID | None = None, trigger: str = "manual"
) -> int:
    """Build and save a new active ICP version inside an ICP_BUILD run. Returns the version number."""
    async with agent_run(tenant_id, AgentRunKind.ICP_BUILD, trigger=trigger, input={}, run_id=run_id) as run:
        settings = await get_settings_for(session, tenant_id)
        knowledge_text = await load_knowledge_text(session, tenant_id)
        await run.step(
            StepType.DECISION,
            "icp_builder.inputs",
            output={
                "products": len(settings.products or []),
                "regions": [r.get("governorate") for r in settings.target_regions or []],
                "knowledge_chars": len(knowledge_text),
            },
        )
        try:
            profile, icp = await icp_builder.build_icp(run, settings=settings, knowledge_text=knowledge_text)
        except LLMRefused as exc:
            raise IcpBuildError(
                "The AI model refused to build the profile. Check the uploaded files."
            ) from exc
        except LLMOutputTruncated as exc:
            raise IcpBuildError("The AI answer was cut off. Try again, or upload shorter files.") from exc
        except LLMInvalidOutput as exc:
            raise IcpBuildError("The AI returned an invalid profile twice. Please try again.") from exc

        version = await icp_service.save_version(
            session,
            tenant_id,
            profile,
            icp,
            source="agent",
            notes=f"Generated by {icp_builder.PROMPT_VERSION}",
        )
        await session.commit()
        run.output_summary = {
            "version": version,
            "target_business_types": len(icp.target_business_types),
            "regions": [r.governorate for r in icp.regions],
        }
        return version


async def job_build_icp(ctx: dict[str, Any], tenant_id: str, run_id: str | None = None) -> dict[str, Any]:
    tid = uuid.UUID(str(tenant_id))
    rid = uuid.UUID(str(run_id)) if run_id else None
    async with SessionLocal() as session:
        try:
            version = await run_icp_build(session, tid, run_id=rid)
        except IcpBuildError as exc:  # already recorded on the run; no traceback noise in the worker log
            logger.warning("ICP build failed for tenant %s: %s", tid, exc)
            return {"status": "failed", "error": str(exc)}
    return {"status": "succeeded", "version": version}
